// Convenience accessors
export const getProject = (slug) => projects.find((p) => p.slug === slug);
export const getByCategory = (cat) => projects.filter((p) => p.category === cat);
export const getNextInCategory = (slug) => {
  const idx = projects.findIndex((p) => p.slug === slug);
  if (idx < 0) return null;
  const cat = projects[idx].category;
  const same = projects.filter((p) => p.category === cat);
  const myIdx = same.findIndex((p) => p.slug === slug);
  return same[(myIdx + 1) % same.length] || null;
};

